// Neutral SVG avatars for channels
export const createAvatar = (text: string, color: string = '#6D3DF5') => {
  const initials = text
    .split(' ')
    .map((w) => w[0])
    .slice(0, 2)
    .join('')
    .toUpperCase();
  return `data:image/svg+xml;utf8,<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64"><rect width="64" height="64" rx="32" fill="${encodeURIComponent(
    color
  )}"/><text x="32" y="38" font-family="-apple-system,BlinkMacSystemFont,sans-serif" font-size="22" font-weight="700" fill="%23ffffff" text-anchor="middle">${initials}</text></svg>`;
};

